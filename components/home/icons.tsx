/** Lucide icon for an admin/home icon name; `fallback` when unknown. */
export function homeIcon(name: string | null | undefined, fallback: LucideIcon = Package): LucideIcon {
    const key = String(name ?? '')
        .trim()
        .toLowerCase()
        .replace(/^fa[srlb]?[\s-]+/, '')
        .replace(/^(fa-)?(solid|regular|light|brands)\s+/, '')
        .replace(/^fa-/, '')
    return ICONS[key] ?? fallback
}
