import { SESSION_HINT_COOKIE } from './lib/session-hint'

type D1Like = {
    prepare(sql: string): {
        bind(...values: unknown[]): { run(): Promise<unknown> }
        all(): Promise<{ results?: Record<string, unknown>[] }>
    }
}
type Env = {
    CRON_SECRET?: string
    NEXT_PUBLIC_BASE_URL?: string
    DB?: D1Like
    ASSETS?: { fetch(request: Request): Promise<Response> }
}
type Ctx = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void }

// ---- content version (site_settings.cache_version) and maintenance switch (site_settings.maintenance_mode) ----

type EdgeSettings = { version: string; maintenance: boolean }

// Only resolved values are memoized (never a promise shared between requests)
let settingsMemo: { value: EdgeSettings; at: number } | null = null

async function getEdgeSettings(env: Env): Promise<EdgeSettings | null> {
    const now = Date.now()
    if (settingsMemo && now - settingsMemo.at < CACHE_VERSION_MEMO_MS) return settingsMemo.value
    if (!env.DB) return null
    try {
        const { results } = await env.DB.prepare(
            "SELECT key, value FROM site_settings WHERE key IN ('cache_version', 'maintenance_mode')"
        ).all()
        const kv = new Map((results ?? []).map(row => [String(row.key), row.value]))
        const maintenance = kv.get('maintenance_mode')
        const value: EdgeSettings = {
            version: kv.get('cache_version') ? String(kv.get('cache_version')) : '0',
            // same parsing as lib/catalog.ts (the flag LayoutProvider renders from)
            maintenance: maintenance === true || maintenance === 1 || maintenance === '1' || maintenance === 'true',
        }
        settingsMemo = { value, at: now }
        return value
    } catch (error) {
        console.error('[edge-cache] reading cache_version / maintenance_mode failed', error)
        return null
    }
}

// Called after successful content writes and after the price cron. A new value orphans every cached
// entry (the version is part of the cache key); orphans expire on their own after the TTL.
async function bumpCacheVersion(env: Env): Promise<void> {
    if (!env.DB) return
    const value = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
    await env.DB.prepare(
        "INSERT OR REPLACE INTO site_settings (key, value, updated_at) VALUES ('cache_version', ?, CURRENT_TIMESTAMP)"
    ).bind(value).run()
    // Re-read both values on the next request: the same write may have switched maintenance on or off
    settingsMemo = null
}

// ---- deployed build id: cached HTML references /_next/static/<build id>/, so it is part of the key ----

let buildIdMemo: string | null = null

async function getBuildId(env: Env): Promise<string | null> {
    if (buildIdMemo) return buildIdMemo
    if (!env.ASSETS) return null
    try {
        // OpenNext copies .next/BUILD_ID into the static assets
        const res = await env.ASSETS.fetch(new Request('https://assets.local/BUILD_ID'))
        const text = res.ok ? (await res.text()).trim() : ''
        if (!/^[\w-]{1,64}$/.test(text)) return null
        buildIdMemo = text
        return text
    } catch (error) {
        console.error('[edge-cache] reading BUILD_ID failed', error)
        return null
    }
}

// ---- helpers ----

function withCacheStatus(response: Response, status: 'HIT' | 'MISS' | 'BYPASS'): Response {
    const out = new Response(response.body, response)
    out.headers.set(CACHE_HEADER, status)
    return out
}

const ORIGINAL_CACHE_CONTROL = 'x-onopo-origin-cache-control'

// The stored copy carries our TTL; the client keeps getting the origin's own Cache-Control
function toStoredCopy(response: Response): Response {
    const stored = new Response(response.body, response)
    stored.headers.set(ORIGINAL_CACHE_CONTROL, response.headers.get('cache-control') ?? '')
    stored.headers.set('Cache-Control', `public, max-age=${EDGE_CACHE_TTL_SECONDS}`)
    stored.headers.delete('Expires')
    stored.headers.delete(CACHE_HEADER)
    return stored
}

function fromStoredCopy(stored: Response): Response {
    const out = new Response(stored.body, stored)
    const original = out.headers.get(ORIGINAL_CACHE_CONTROL)
    out.headers.delete(ORIGINAL_CACHE_CONTROL)
    if (original) out.headers.set('Cache-Control', original)
    else out.headers.delete('Cache-Control')
    out.headers.set(CACHE_HEADER, 'HIT')
    return out
}

// The maintenance render (lib/edge-cache.ts isMaintenanceBody) as a temporary outage: crawlers keep the
// indexed page and retry later, and nothing stores it
function maintenanceResponse(body: string, origin: Response): Response {
    const headers = new Headers(origin.headers)
    for (const [name, value] of Object.entries(maintenanceHeaders())) headers.set(name, value)
    headers.set(CACHE_HEADER, 'BYPASS')
    headers.delete('content-length')
    return new Response(body, { status: 503, statusText: 'Service Unavailable', headers })
}

// Client-side (RSC) navigation of a store page while maintenance is on (lib/edge-cache.ts
// blocksRscDuringMaintenance): not a Flight payload, so the Next router does a full page load instead
function maintenanceRscResponse(): Response {
    const headers = new Headers(maintenanceHeaders())
    headers.set('Content-Type', 'text/plain; charset=utf-8')
    headers.set(CACHE_HEADER, 'BYPASS')
    return new Response('Site kısa bir bakımda.', { status: 503, statusText: 'Service Unavailable', headers })
}

// Responses that are not served from or stored in the edge cache. While maintenance is on, store-page HTML
// is read so the maintenance render can be answered as 503.
async function passThrough(response: Response, url: URL, method: string, settings: EdgeSettings | null): Promise<Response> {
    const contentType = response.headers.get('content-type')
    if (method === 'GET' && settings?.maintenance && mayRenderMaintenance(url.pathname) && needsBodyCheck(contentType)) {
        const body = await response.text()
        if (isMaintenanceBody(contentType, body)) return maintenanceResponse(body, response)
        return withCacheStatus(new Response(body, response), 'BYPASS')
    }
    return withCacheStatus(response, 'BYPASS')
}

function setCookiesOf(headers: Headers): string[] {
    const h = headers as Headers & { getSetCookie?: () => string[]; getAll?: (name: string) => string[] }
    if (typeof h.getSetCookie === 'function') return h.getSetCookie()
    if (typeof h.getAll === 'function') return h.getAll('set-cookie')
    const single = headers.get('set-cookie')
    return single ? [single] : []
}

// Server-to-server endpoints (PayTR, BirFatura) are answered exactly as Next sends them
const NO_SESSION_HINT = /^\/api\/(birfatura|payment)(\/|$)/

// Adds the Set-Cookie that keeps the readable session hint in line with auth_token (outgoing response only:
// stored edge-cache copies are made before this runs)
function withSessionHint(request: Request, url: URL, response: Response): Response {
    if (NO_SESSION_HINT.test(url.pathname)) return response
    const line = sessionHintSetCookie(SESSION_HINT_COOKIE, request.headers.get('cookie'), setCookiesOf(response.headers))
    if (!line) return response
    const out = new Response(response.body, response)
    out.headers.append('Set-Cookie', line)
    return out
}

// A same-origin redirect of a request whose tracking parameters were stripped gets them back in its Location
// (lib/edge-cache.ts restoreTrackingParams), e.g. Next's trailing-slash 308
function withTrackingParams(response: Response, requestUrl: URL, renderedUrl: URL): Response {
    const location = restoreTrackingParams(response.status, response.headers.get('location'), requestUrl, renderedUrl)
    if (!location) return response
    const out = new Response(response.body, response)
    out.headers.set('Location', location)
    return out
}

function edgeCache(): Cache | null {
    try {
        return (globalThis as any).caches?.default ?? null
    } catch {
        return null
    }
}

async function serveFromEdgeCache(request: Request, url: URL, env: Env, ctx: Ctx): Promise<Response> {
    const cache = edgeCache()
    const [buildId, settings] = await Promise.all([getBuildId(env), getEdgeSettings(env)])
    // During maintenance nothing is served from or written to the cache
    if (!cache || !buildId || !settings || settings.maintenance) {
        return passThrough(await handler.fetch(request, env, ctx), url, request.method, settings)
    }

    const key = new Request(cacheKeyUrl(url, buildId, settings.version))
    try {
        const hit = await cache.match(key)
        if (hit) {
            const out = fromStoredCopy(hit)
            if (needsBodyCheck(out.headers.get('content-type'))) out.headers.set('Cache-Control', ANONYMOUS_HTML_CACHE_CONTROL)
            return out
        }
    } catch (error) {
        console.error('[edge-cache] match failed', error)
    }

    let response: Response = await handler.fetch(request, env, ctx)
    if (!isStorableResponse(response)) return withCacheStatus(response, 'BYPASS')

    // HTML is read once so its body can be checked (maintenance render, no-cache marker, product page block).
    // Only misses of allowlisted anonymous pages are buffered; their data is loaded before the HTML streams anyway.
    const contentType = response.headers.get('content-type')
    const isHtml = needsBodyCheck(contentType)
    if (isHtml) {
        const body = await response.text()
        response = new Response(body, response)
        // The maintenance switch was turned on within the settings memo window
        if (isMaintenanceBody(contentType, body)) return maintenanceResponse(body, response)
        if (!isStorableBody(url.pathname, contentType, body)) return withCacheStatus(response, 'BYPASS')
    }

    ctx.waitUntil(cache.put(key, toStoredCopy(response.clone())).catch(error => {
        console.error('[edge-cache] put failed', error)
    }))
    const out = withCacheStatus(response, 'MISS')
    if (isHtml) out.headers.set('Cache-Control', ANONYMOUS_HTML_CACHE_CONTROL)
    return out
}

const worker = {
    async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
        const url = new URL(request.url)
        const method = request.method

        const redirectTo = canonicalRedirect(url, method)
        if (redirectTo) {
            return new Response(null, {
                status: 301,
                headers: { Location: redirectTo, 'Cache-Control': 'public, max-age=86400' },
            })
        }

        // Writes (checkout, PayTR/BirFatura callbacks, admin saves) are passed through untouched
        if (method !== 'GET' && method !== 'HEAD') {
            const response: Response = await handler.fetch(request, env, ctx)
            if (response.ok && shouldBumpCacheVersion(url.pathname, method, hasAuthCookie(request.headers.get('cookie')))) {
                try {
                    await bumpCacheVersion(env)
                } catch (error) {
                    console.error('[edge-cache] cache_version bump failed', error)
                }
            }
            return withSessionHint(request, url, response)
        }

        // Next renders the page as if tracking parameters weren't there (the cache key ignores them too), so a
        // stored page never carries the first visitor's click ids; a redirect Next answers gets them back
        // (withTrackingParams)
        const clean = stripTrackingParams(url)
        const target = clean ? new Request(clean.href, request) : request
        const targetUrl = clean ?? url
        const finish = (response: Response) =>
            withSessionHint(request, targetUrl, clean ? withTrackingParams(response, url, clean) : response)

        if (isCacheableRequest({ method, url: targetUrl, headers: target.headers })) {
            return finish(await serveFromEdgeCache(target, targetUrl, env, ctx))
        }
        // HEAD of a store page during maintenance: rendered as a GET so the 503 status and headers match
        if (method === 'HEAD' && mayRenderMaintenance(targetUrl.pathname)) {
            const settings = await getEdgeSettings(env)
            if (settings?.maintenance) {
                const get = new Request(targetUrl.href, { method: 'GET', headers: target.headers })
                const full = await passThrough(await handler.fetch(get, env, ctx), targetUrl, 'GET', settings)
                return finish(new Response(null, full))
            }
        }
        const [response, settings] = await Promise.all([
            handler.fetch(target, env, ctx) as Promise<Response>,
            method === 'GET' && mayRenderMaintenance(targetUrl.pathname) ? getEdgeSettings(env) : null,
        ])
        // A client-side navigation during maintenance: the router falls back to a full page load (the 503 page)
        if (settings?.maintenance && isRscRequest(target.headers, targetUrl) && blocksRscDuringMaintenance(targetUrl.pathname)) {
            await response.body?.cancel().catch(() => {})
            return finish(maintenanceRscResponse())
        }
        return finish(await passThrough(response, targetUrl, method, settings))
    },

    // Triggered by [triggers] crons in wrangler.toml (0 7 * * * = 10:00 Turkey time)
    async scheduled(controller: { cron: string }, env: Env, ctx: Ctx) {
        if (!env.CRON_SECRET) {
            console.error('[cron] CRON_SECRET is not set, skipping price update')
            return
        }

        // Call the route in-process; the trailing slash matches next.config trailingSlash
        const baseUrl = env.NEXT_PUBLIC_BASE_URL || 'https://onopostore.com'
        const request = new Request(`${baseUrl}/api/cron/update-prices/`, {
            headers: { Authorization: `Bearer ${env.CRON_SECRET}` },
        })

        const response: Response = await handler.fetch(request, env, ctx)
        const body = await response.text()
        if (response.ok) {
            console.log(`[cron] ${controller.cron} price update ok: ${body}`)
            // Prices changed: cached pages and JSON must not keep showing the old ones
            try {
                await bumpCacheVersion(env)
            } catch (error) {
                console.error('[cron] cache_version bump failed', error)
            }
        } else {
            // Throwing marks the cron invocation as failed in the Cloudflare dashboard
            throw new Error(`[cron] ${controller.cron} price update failed (${response.status}): ${body}`)
        }
    },
}

export default worker

