    CACHE_HEADER,
    CACHE_VERSION_MEMO_MS,
    EDGE_CACHE_TTL_SECONDS,
    blocksRscDuringMaintenance,
    cacheKeyUrl,
    canonicalRedirect,
    hasAuthCookie,
    isCacheableRequest,
    isMaintenanceBody,
    isRscRequest,
    isStorableBody,
    isStorableResponse,
    maintenanceHeaders,
    mayRenderMaintenance,
    needsBodyCheck,
    restoreTrackingParams,
